/**
 * One-off D1 bootstrap runner.
 *
 * WHY THIS EXISTS: the repository's CLOUDFLARE_API_TOKEN carries Workers:Edit
 * (CD deploys fine) but not D1:Edit, so `wrangler d1 migrations apply --remote`
 * fails with 7403. This Worker is a temporary bridge: it is deployed by
 * .github/workflows/db-bootstrap.yml, runs migrations/0012_operators.sql
 * through the Worker's own D1 binding, reports what exists, and is deleted in
 * the same job. Additive DDL only (CREATE TABLE IF NOT EXISTS + INSERT OR
 * IGNORE), so a re-run is a no-op.
 *
 * It never reads application data and refuses to run without the per-run key.
 * Every failure answers with JSON naming the step, so the CI log says what
 * broke instead of only "error code: 1101".
 */
// migration.mjs is generated by scripts/d1-bootstrap/inline-sql.mjs at deploy
// time from migrations/0012_operators.sql. Inlining keeps the bundle free of
// text-module rules, which do not reach files outside this Worker's directory.
import migrationSql from './migration.mjs';

/** Split a migration into statements.
 *
 * D1's `exec()` is line-oriented (it treats every line as its own statement), so
 * it cannot run a multi-line migration file. Comments are stripped first, then
 * the text is split on `;` — the migration has no semicolons inside literals.
 */
function statementsOf(sql) {
  const cleaned = sql
    .split(/\r?\n/)
    .filter((line) => !line.trim().startsWith('--'))
    .join('\n');
  return cleaned
    .split(';')
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
}

async function applyMigration(db) {
  const statements = statementsOf(migrationSql);
  const results = [];
  for (let index = 0; index < statements.length; index += 1) {
    const statement = statements[index];
    const head = statement.slice(0, 48).replace(/\s+/g, ' ');
    try {
      await db.prepare(statement).run();
      results.push({ index, ok: true });
    } catch (error) {
      const message = String(error && error.message ? error.message : error);
      // Re-running a partially applied migration is expected: ADD COLUMN and
      // index creation are not IF NOT EXISTS in older SQLite paths.
      const benign = /duplicate column name|already exists/i.test(message);
      results.push(benign ? { index, ok: true, skipped: message } : { index, ok: false, error: message, statement: head });
    }
  }
  return results;
}

async function names(db, sql) {
  try {
    const result = await db.prepare(sql).all();
    return (result.results ?? []).map((row) => Object.values(row)[0]);
  } catch (error) {
    return { error: String(error && error.message ? error.message : error) };
  }
}

export default {
  async fetch(request, env) {
    let step = 'start';
    try {
      const url = new URL(request.url);
      if (url.pathname !== '/apply') return new Response('not found', { status: 404 });

      const key = request.headers.get('x-bootstrap-key') ?? url.searchParams.get('key') ?? '';
      if (!env.BOOTSTRAP_KEY || key !== env.BOOTSTRAP_KEY) {
        return new Response('forbidden', { status: 403 });
      }

      const startedAt = Date.now();
      step = 'apply';
      let results = [];
      let applyError = null;
      try {
        results = await applyMigration(env.DB);
      } catch (error) {
        applyError = String(error && error.message ? error.message : error);
      }

      const failures = results.filter((row) => !row.ok);
      step = 'report';
      return Response.json({
        applied: Boolean(results.length) && failures.length === 0 && !applyError,
        error: applyError,
        statements: results.length,
        skipped: results.filter((row) => row.skipped).length,
        failures,
        ms: Date.now() - startedAt,
        tables: await names(
          env.DB,
          "SELECT name FROM sqlite_master WHERE type = 'table' AND name LIKE 'operator%' ORDER BY name",
        ),
        permissions: await names(env.DB, "SELECT key FROM permissions WHERE key LIKE 'operator.%' ORDER BY key"),
      });
    } catch (error) {
      return Response.json(
        { applied: false, stage: step, error: String(error && error.stack ? error.stack : error) },
        { status: 500 },
      );
    }
  },
};
